cues = []
for l in L:
    if cues and cues[-1]['open']:
        c = cues[-1]; c['en'] += ' ' + l['text']; c['words'] += l['words']; c['t1'] = l['t1']
        c['open'] = l['text'] in MERGE
    else:
        cues.append(dict(en=l['text'], words=list(l['words']), t0=l['t0'], t1=l['t1'], open=l['text'] in MERGE))
out = []
for i, c in enumerate(cues):
    en = c['en']
    if en not in ZH: raise SystemExit('no zh for: ' + en)
    out.append(dict(id=f'L{i+1:02d}', en=en, zh=ZH[en], t0=c['t0'], t1=c['t1'], words=[[w['w'], w['t0']] for w in c['words']]))
open(os.path.join(HERE, 'js/lyrics.js'), 'w').write('// generated by tools/make_lyrics.py from data/lyrics_aligned.json: sung lines, word starts, Chinese translation\nexport const LYRICS = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
for c in out: print(f"{c['t0']:7.2f} {c['t1']:7.2f} {c['en']}")
